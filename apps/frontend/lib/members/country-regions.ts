/** The countries in any of the given regions, in ALL_COUNTRIES order; every country when none is given. */
export function countriesInRegions(regions: readonly string[]): string[] {
  if (regions.length === 0) return ALL_COUNTRIES;
  const allowed = new Set(regions.flatMap((r) => REGION_COUNTRIES[r as ApplicationRegion] ?? []));
  return ALL_COUNTRIES.filter((c) => allowed.has(c));
}

